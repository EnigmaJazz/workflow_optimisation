"""Compare the sandbox plugins installed in the V2 config root with their sources (queue Q44, section 6 on V2).

usage: v2-sandbox-plugins-check.py <sandbox-repo> <v2-plugins-dir>
Prints one line: clean|error <TAB> detail.

The authoritative list is V2_PLUGIN_FILES in <sandbox-repo>/scripts/secure-launcher-v2.conf ("<repo path>|<path under the plugins
dir>"), the same list the installer and rollback use. These files are installed by hand from the sandbox repository, not
generated by derive, so section 0's derive check does not cover them. Read-only."""
import re
import sys
from pathlib import Path


def main(argv):
    repo, plugins = Path(argv[1]), Path(argv[2])
    conf = repo / "scripts" / "secure-launcher-v2.conf"
    try:
        text = conf.read_text(encoding="utf-8")
    except OSError as exc:
        print(f"error\tcannot read the V2 install list {conf}: {exc}")
        return 0
    block = re.search(r"V2_PLUGIN_FILES=\((.*?)\n\)", text, re.S)
    pairs = re.findall(r'"([^"|]+)\|([^"|]+)"', block.group(1)) if block else []
    if not pairs:
        print(f"error\tno V2_PLUGIN_FILES entries found in {conf}")
        return 0
    missing, drifted = [], []
    for source, dest in pairs:
        src, dst = repo / source, plugins / dest
        if not src.is_file():
            drifted.append(f"{dest} (source {source} is missing)")
        elif not dst.is_file():
            missing.append(dest)
        elif src.read_bytes() != dst.read_bytes():
            drifted.append(dest)
    if missing or drifted:
        parts = []
        if missing:
            parts.append(f"{len(missing)} not installed ({', '.join(missing[:4])})")
        if drifted:
            parts.append(f"{len(drifted)} differ from source ({', '.join(drifted[:4])})")
        print("error\t" + "; ".join(parts) + "; reinstall with scripts/install-user-files-v2")
        return 0
    print(f"clean\tall {len(pairs)} sandbox plugin files match their sources")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
